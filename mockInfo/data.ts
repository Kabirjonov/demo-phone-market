export function slugifyProduct(title: string) {
	return title
		.toLowerCase()
		.normalize("NFKD")
		.replace(/[\u0300-\u036f]/g, "")
		.replace(/[^a-z0-9]+/g, "-")
		.replace(/^-+|-+$/g, "");
}

export function getProductBySlug(slug: string) {
	return hitProducts.find(product => slugifyProduct(product.title) === slug);
}

